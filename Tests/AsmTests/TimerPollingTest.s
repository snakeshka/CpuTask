; ====================================================================
; Тест опроса таймера
; ====================================================================

; Запоминаем стартовое число тактов
_SIM_GET_TICK R1

; Заводим таймер на 32 такта (CNTD = 0xE010)
LI R0 0xE010
LI R2 32
STW R2 R0 0          ; CNTD = 32

; Сбрасываем TRIG (CTRL = 0xE014)
LI R3 0xE014
LI R4 0
STB R4 R3 0          ; CTRL = 0 (TRIG=0, IE=0)
LI R15 1             ; Маска бита TRIG (bit 0)

; Опрос в цикле
POLL_LOOP:
LDB R5 R3 0          ; Чтение CTRL
AND R6 R5 R15        ; Маска бита TRIG (bit 0)
BRZ R6 POLL_LOOP     ; Опрашиваем, пока TRIG != 1

; Фиксируем конечное время тактов
_SIM_GET_TICK R7
SUB R8 R7 R1         ; R8 = R7 - R1 (прошедшие такты)

; Проверяем, что прошло не менее 32 тактов
SLT R9 R8 R2         ; Если elapsed < 32, R9 = 1
BRNZ R9 FAIL         ; Если мало тактов то ошибка
_SIM_HALTI 0         ; Успешное завершение теста (код 0)
FAIL:
_SIM_HALTI 1         ; Ошибка (код 1)